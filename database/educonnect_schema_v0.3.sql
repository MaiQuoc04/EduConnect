-- Supabase publishes the public schema through its REST API. Our app talks to the DB only through the Node server
-- (role postgres, which bypasses RLS), so RLS is turned on with no policies: the REST API sees nothing.
DO $$
DECLARE t text;
BEGIN
  FOR t IN SELECT tablename FROM pg_tables WHERE schemaname = 'public' LOOP
    EXECUTE format('ALTER TABLE public.%I ENABLE ROW LEVEL SECURITY', t);
  END LOOP;
END $$;

