-- Written by Anh (FE-08 School Feed), 17/11/2026. Same definition as in educonnect_schema_v0.3.sql.
-- Patch for a database already created from schema v0.3: users can REPORT a comment to the person who moderates it.
-- New table comment_reports (52 tables).
--   It points to a COMMENT, never to a post: comments already carry post_id (group feed, FE-05) or school_post_id
--   (school feed, FE-08), so both feeds use the same rows without a schema change. Who handles a report is decided by
--   the server (FE-08: the School Manager, only for comments of school posts; FE-05: the homeroom teacher / group
--   moderator, only for comments of their group's posts).
--   reason: one code from a fixed list (comment_reports_reason_check). The client shows it in Vietnamese:
--     INAPPROPRIATE_LANGUAGE  Ngôn từ không phù hợp
--     HARASSMENT              Quấy rối, xúc phạm hoặc bắt nạt
--     SPAM                    Spam, quảng cáo hoặc nội dung lặp lại
--     FALSE_INFORMATION       Thông tin sai sự thật
--     OTHER                   Lý do khác (the server asks for a note)
--   note: free text, optional (up to 500 characters).
--   status: PENDING (waiting), RESOLVED (the comment was deleted), DISMISSED (kept: nothing wrong).
--     resolved_by / resolved_at are set together, when the status leaves PENDING (comment_reports_resolved_check).
--   UNIQUE (comment_id, reported_by): one person reports one comment once (a second report changes nothing).
--   deleted_at: business rules §14 (soft delete everywhere); nothing deletes a report today.
-- A report never deletes or hides anything by itself: the comment is only deleted (soft, business rules §5 "deleted,
-- never hidden") when the moderator decides so.
-- How to run (team lead): Supabase > SQL Editor > paste > Run. Once; running it again changes nothing.

BEGIN;

CREATE TABLE IF NOT EXISTS comment_reports (
  report_id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  comment_id  BIGINT NOT NULL,
  reported_by BIGINT NOT NULL,
  reason      VARCHAR(50) NOT NULL,
  note        VARCHAR(500) NULL,
  status      VARCHAR(20) NOT NULL DEFAULT 'PENDING',
  resolved_by BIGINT NULL,
  resolved_at TIMESTAMPTZ NULL,
  created_at  TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  deleted_at  TIMESTAMPTZ NULL
);
ALTER TABLE comment_reports ENABLE ROW LEVEL SECURITY;   -- like every table: only the Node server reads it

-- ADD CONSTRAINT has no IF NOT EXISTS: every constraint is added only when missing, so a second run changes nothing.
-- The names are the ones PostgreSQL gives the inline constraints of the schema file, so both ways end up the same.
DO $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_constraint
                 WHERE conrelid = 'comment_reports'::regclass AND conname = 'comment_reports_comment_id_fkey') THEN
    ALTER TABLE comment_reports ADD CONSTRAINT comment_reports_comment_id_fkey
      FOREIGN KEY (comment_id) REFERENCES comments(comment_id);
  END IF;

  IF NOT EXISTS (SELECT 1 FROM pg_constraint
                 WHERE conrelid = 'comment_reports'::regclass AND conname = 'comment_reports_reported_by_fkey') THEN
    ALTER TABLE comment_reports ADD CONSTRAINT comment_reports_reported_by_fkey
      FOREIGN KEY (reported_by) REFERENCES users(user_id);
  END IF;

  IF NOT EXISTS (SELECT 1 FROM pg_constraint
                 WHERE conrelid = 'comment_reports'::regclass AND conname = 'comment_reports_resolved_by_fkey') THEN
    ALTER TABLE comment_reports ADD CONSTRAINT comment_reports_resolved_by_fkey
      FOREIGN KEY (resolved_by) REFERENCES users(user_id);
  END IF;

  IF NOT EXISTS (SELECT 1 FROM pg_constraint
                 WHERE conrelid = 'comment_reports'::regclass AND conname = 'comment_reports_comment_id_reported_by_key') THEN
    ALTER TABLE comment_reports ADD CONSTRAINT comment_reports_comment_id_reported_by_key
      UNIQUE (comment_id, reported_by);
  END IF;

  IF NOT EXISTS (SELECT 1 FROM pg_constraint
                 WHERE conrelid = 'comment_reports'::regclass AND conname = 'comment_reports_reason_check') THEN
    ALTER TABLE comment_reports ADD CONSTRAINT comment_reports_reason_check
      CHECK (reason IN ('INAPPROPRIATE_LANGUAGE','HARASSMENT','SPAM','FALSE_INFORMATION','OTHER'));
  END IF;

  IF NOT EXISTS (SELECT 1 FROM pg_constraint
                 WHERE conrelid = 'comment_reports'::regclass AND conname = 'comment_reports_status_check') THEN
    ALTER TABLE comment_reports ADD CONSTRAINT comment_reports_status_check
      CHECK (status IN ('PENDING','RESOLVED','DISMISSED'));
  END IF;

  IF NOT EXISTS (SELECT 1 FROM pg_constraint
                 WHERE conrelid = 'comment_reports'::regclass AND conname = 'comment_reports_resolved_check') THEN
    ALTER TABLE comment_reports ADD CONSTRAINT comment_reports_resolved_check
      CHECK ((status = 'PENDING') = (resolved_at IS NULL) AND (resolved_at IS NULL) = (resolved_by IS NULL));
  END IF;
END $$;

-- The moderator's queue reads the waiting reports by comment; "already reported by me" reads by comment too (the
-- UNIQUE index above covers comment_id first).
CREATE INDEX IF NOT EXISTS idx_comment_reports_status ON comment_reports (status, comment_id);

COMMIT;
