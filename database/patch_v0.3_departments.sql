-- Patch for a database already created from schema v0.3 (02/11/2026, FE-03): the list of departments (tổ chuyên môn).
-- On Update Teacher (UC-17) the School Manager picks a department from this list instead of typing it, so one
-- department is always written the same way. Same definition as in educonnect_schema_v0.3.sql.
-- teachers.department keeps the department NAME (no foreign key yet: FE-13 create / import still accept free text).
-- How to run: Supabase > SQL Editor > paste > Run (once). Then check the list (last SELECT) and merge near-duplicates
-- by hand if any (e.g. "Tổ Toán" / "Tổ toán"): UPDATE teachers SET department = '<kept name>' WHERE department = '<other>';
-- UPDATE departments SET deleted_at = NOW() WHERE department_name = '<other>';

BEGIN;

CREATE TABLE IF NOT EXISTS departments (
  department_id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  department_name VARCHAR(100) NOT NULL UNIQUE,
  deleted_at      TIMESTAMPTZ NULL
);
ALTER TABLE departments ENABLE ROW LEVEL SECURITY;   -- like every table: only the Node server reads it

-- Same spelling everywhere: trim and collapse spaces in the names already on teacher profiles…
UPDATE teachers SET department = NULLIF(btrim(regexp_replace(department, '\s+', ' ', 'g')), '')
WHERE department IS NOT NULL AND department IS DISTINCT FROM NULLIF(btrim(regexp_replace(department, '\s+', ' ', 'g')), '');

-- …and start the list from them.
INSERT INTO departments (department_name)
SELECT DISTINCT department FROM teachers WHERE department IS NOT NULL
ON CONFLICT (department_name) DO NOTHING;

COMMIT;

SELECT d.department_name, COUNT(t.teacher_id) AS teachers
FROM departments d LEFT JOIN teachers t ON t.department = d.department_name
WHERE d.deleted_at IS NULL
GROUP BY d.department_name ORDER BY d.department_name;
