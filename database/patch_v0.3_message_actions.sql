-- Approved by the team lead 07/11/2026 (Khanh). Same definitions as in educonnect_schema_v0.3.sql.
-- Patch for a database already created from schema v0.3: FE-06 reply, reactions, delete message.
-- The code on feature/fe-06-messaging needs this patch: without it every chat screen fails. Run on the shared DB 07/11/2026.
-- How to run: Supabase > SQL Editor > paste > Run (once).

BEGIN;

-- Reply: one level, the quote is read from the original message when shown.
-- Delete for everyone: a separate column, because every query filters deleted_at and the message must stay in the
-- chat as "Tin nhắn đã được xoá". The content stays in the database; the API never returns it.
ALTER TABLE messages
  ADD COLUMN IF NOT EXISTS reply_to_message_id BIGINT NULL REFERENCES messages(message_id),
  ADD COLUMN IF NOT EXISTS deleted_for_everyone_at TIMESTAMPTZ NULL,
  ADD COLUMN IF NOT EXISTS deleted_for_everyone_by BIGINT NULL REFERENCES users(user_id);

-- Delete for me: one row per person who removed the message from their own view. Rows are never removed.
CREATE TABLE IF NOT EXISTS message_user_deletions (
  message_id BIGINT NOT NULL REFERENCES messages(message_id),
  user_id    BIGINT NOT NULL REFERENCES users(user_id),
  deleted_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (message_id, user_id)
);
ALTER TABLE message_user_deletions ENABLE ROW LEVEL SECURITY;   -- like every table: only the Node server reads it

-- One reaction per person per message; removing a reaction removes the row (hard delete, like post_likes).
CREATE TABLE IF NOT EXISTS message_reactions (
  reaction_id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  message_id    BIGINT NOT NULL REFERENCES messages(message_id),
  user_id       BIGINT NOT NULL REFERENCES users(user_id),
  reaction_code VARCHAR(10) NOT NULL,
  created_at    TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  UNIQUE (message_id, user_id),
  CHECK (reaction_code IN ('LIKE','LOVE','HAHA','WOW','SAD','THANKS'))
);
ALTER TABLE message_reactions ENABLE ROW LEVEL SECURITY;

INSERT INTO system_settings (setting_key, setting_value, description)
VALUES ('chat.delete_for_everyone_minutes', '15', 'Time allowed to delete a chat message for everyone (minutes)')
ON CONFLICT (setting_key) DO NOTHING;

COMMIT;
