-- Patch for a database already created from schema v0.3 (27/10/2026): adds password_reset_requests.
-- Same definition as in educonnect_schema_v0.3.sql. How to run: Supabase > SQL Editor > paste > Run (once).

CREATE TABLE password_reset_requests (
  request_id  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id     BIGINT NOT NULL,
  reason      VARCHAR(500) NULL,
  status      VARCHAR(20) NOT NULL DEFAULT 'PENDING',  -- PENDING, DONE, REJECTED
  handled_by  BIGINT NULL,
  handled_at  TIMESTAMPTZ NULL,
  created_at  TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  FOREIGN KEY (user_id)    REFERENCES users(user_id),
  FOREIGN KEY (handled_by) REFERENCES users(user_id),
  CHECK (status IN ('PENDING','DONE','REJECTED'))
);

CREATE UNIQUE INDEX uq_password_reset_requests_pending ON password_reset_requests (user_id) WHERE status = 'PENDING';
