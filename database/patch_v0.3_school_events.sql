-- School calendar ("Lịch sắp tới của trường", Stitch SCR-34 right column): school-wide dates set by the School
-- Manager – exams, ceremonies, meetings. Class events stay in class_events (a class_id is required there), so the
-- school calendar gets its own table.
--   grade_level_id NULL = the whole school; otherwise one grade (e.g. "Toàn khối 10").
--   Soft delete like every other table (deleted_at / deleted_by).
-- Same definition as in educonnect_schema_v0.3.sql. How to run: Supabase > SQL Editor > paste > Run (once; running it
-- again changes nothing).

BEGIN;

CREATE TABLE IF NOT EXISTS school_events (
  event_id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  school_year_id BIGINT NOT NULL,
  grade_level_id BIGINT NULL,                    -- NULL = whole school
  title          VARCHAR(255) NOT NULL,
  description    TEXT NULL,
  location       VARCHAR(255) NULL,
  start_at       TIMESTAMPTZ NOT NULL,
  end_at         TIMESTAMPTZ NULL,
  created_by     BIGINT NOT NULL,
  created_at     TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_by     BIGINT NULL,
  updated_at     TIMESTAMPTZ NULL,
  deleted_by     BIGINT NULL,
  deleted_at     TIMESTAMPTZ NULL,
  CHECK (end_at IS NULL OR end_at > start_at),
  FOREIGN KEY (school_year_id) REFERENCES school_years(school_year_id),
  FOREIGN KEY (grade_level_id) REFERENCES grade_levels(grade_level_id),
  FOREIGN KEY (created_by)     REFERENCES users(user_id),
  FOREIGN KEY (updated_by)     REFERENCES users(user_id),
  FOREIGN KEY (deleted_by)     REFERENCES users(user_id)
);
CREATE INDEX IF NOT EXISTS idx_school_events_start ON school_events (start_at) WHERE deleted_at IS NULL;

COMMIT;

