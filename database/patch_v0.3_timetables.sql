-- Patch for a database already created from schema v0.3 (10/11/2026, FE-10 timetable, agreed with the lead): the
-- weekly pattern of a class timetable is stored, so it can be shown and edited again (UC-71, UC-73).
--   timetables         = one version of a class timetable, valid from start_date to end_date (versions of a class
--                        never overlap; a change from date X ends the running version on X-1 and starts a new one).
--   timetable_entries  = the weekly pattern of a version: weekday + period -> subject (+ room). The teacher is NOT
--                        stored: each generated period takes the teacher of the teaching assignment that covers its
--                        date (business rules §4, §10: no substitute teaching).
-- timetable_slots (one row per period per day) are generated from these rows. Same definition as in
-- educonnect_schema_v0.3.sql.
-- How to run: Supabase > SQL Editor > paste > Run (once; running it again changes nothing).

BEGIN;

CREATE TABLE IF NOT EXISTS timetables (
  timetable_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  class_id     BIGINT NOT NULL,
  start_date   DATE NOT NULL,
  end_date     DATE NOT NULL,
  created_by   BIGINT NULL,
  created_at   TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  deleted_at   TIMESTAMPTZ NULL,
  CHECK (end_date >= start_date),
  FOREIGN KEY (class_id)   REFERENCES classes(class_id),
  FOREIGN KEY (created_by) REFERENCES users(user_id)
);
CREATE INDEX IF NOT EXISTS idx_timetables_class ON timetables (class_id, start_date) WHERE deleted_at IS NULL;

CREATE TABLE IF NOT EXISTS timetable_entries (
  timetable_id BIGINT   NOT NULL,
  weekday      SMALLINT NOT NULL,                  -- ISO: 1 = Monday ... 7 = Sunday
  slot_id      BIGINT   NOT NULL,
  subject_id   BIGINT   NOT NULL,
  room         VARCHAR(50),
  PRIMARY KEY (timetable_id, weekday, slot_id),
  CHECK (weekday BETWEEN 1 AND 7),
  FOREIGN KEY (timetable_id) REFERENCES timetables(timetable_id),
  FOREIGN KEY (slot_id)      REFERENCES time_slots(slot_id),
  FOREIGN KEY (subject_id)   REFERENCES subjects(subject_id)
);

ALTER TABLE timetables ENABLE ROW LEVEL SECURITY;          -- like every table: only the Node server reads them
ALTER TABLE timetable_entries ENABLE ROW LEVEL SECURITY;

COMMIT;

SELECT table_name FROM information_schema.tables
WHERE table_schema = 'public' AND table_name IN ('timetables', 'timetable_entries') ORDER BY table_name;
