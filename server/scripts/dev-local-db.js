// TEMPORARY: the team lead changed Supabase before updating database/educonnect_schema_v0.3.sql, so the local copy
// is brought in line with Supabase right after the seed (checked against information_schema on 2026-10-28):
// - parents.address (TEXT) moved to users.address (VARCHAR(500)); the seeded addresses are copied over.
// - new table password_reset_requests.
// Every statement is guarded, so this becomes a no-op once the repo schema file matches Supabase. Remove it then.
const SUPABASE_SYNC = `
BEGIN;
ALTER TABLE users ADD COLUMN IF NOT EXISTS address VARCHAR(500);
DO $$
BEGIN
  IF EXISTS (SELECT 1 FROM information_schema.columns
             WHERE table_schema = 'public' AND table_name = 'parents' AND column_name = 'address') THEN
    UPDATE users u SET address = p.address FROM parents p WHERE p.user_id = u.user_id AND u.address IS NULL;
    ALTER TABLE parents DROP COLUMN address;
  END IF;
END $$;
CREATE TABLE IF NOT EXISTS password_reset_requests (
  request_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id    BIGINT NOT NULL REFERENCES users(user_id),
  reason     VARCHAR(500),
  status     VARCHAR(20) NOT NULL DEFAULT 'PENDING' CHECK (status IN ('PENDING', 'DONE', 'REJECTED')),
  handled_by BIGINT REFERENCES users(user_id),
  handled_at TIMESTAMPTZ,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE UNIQUE INDEX IF NOT EXISTS uq_password_reset_requests_pending ON password_reset_requests (user_id)
  WHERE status = 'PENDING';
COMMIT;`;

